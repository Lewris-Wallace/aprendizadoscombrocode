amigos = 0
numero = -10
numero2 = 10
lista = [1, 3, 5, 7, 9]
# -
amigo = amigos + 3
amigos += 3
# -[As operações acima são equivalentes, a primeira é uma forma mais detalhada de escrever a segunda.]
# -[E claramente, isso só não incumbe a adição, mas também a subtração, multiplicação, divisão e outras operações matemáticas.]
print(amigos)
print(amigo)
# -[Para comprovar tal fato, podemos imprimir o valor das duas variáveis e verificar que são iguais.]
# -
print(abs(numero)) # A função abs() retorna o valor absoluto de um número, ou seja, o valor sem o sinal negativo.
print(pow(numero2, 3)) # A função pow() retorna o valor de um número elevado a uma potência, sendo o primeiro o número e o segundo a potência.
print(max(lista)) # A função max() retorna o maior valor de uma lista.
print(min(lista)) # A função min() retorna o menor valor de uma lista.